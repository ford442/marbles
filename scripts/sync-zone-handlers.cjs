#!/usr/bin/env node
/**
 * Export the registered zone types (src/zone-setup/registry.js ZONE_TYPES:
 * built-in stamps, lazy factory stamps and v2 primitives) to
 * assets/schemas/zone-handlers.json.
 *
 * Usage:
 *   node scripts/sync-zone-handlers.cjs           # rewrite the JSON
 *   node scripts/sync-zone-handlers.cjs --check   # CI: fail if it is stale
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { pathToFileURL } = require('url');

const REGISTRY_JS = path.join(__dirname, '..', 'src', 'zone-setup', 'registry.js');
const OUT = path.join(__dirname, '..', 'assets', 'schemas', 'zone-handlers.json');

function readZoneTypes() {
  // The registry imports TypeScript (primitives.ts); load it in a child Node
  // with type stripping so this works on Node 22 and later.
  const code = `const m = await import(${JSON.stringify(pathToFileURL(REGISTRY_JS).href)});`
    + 'process.stdout.write(JSON.stringify(m.ZONE_TYPES));';
  const res = spawnSync(
    process.execPath,
    ['--experimental-strip-types', '--no-warnings', '--input-type=module', '-e', code],
    { encoding: 'utf8' },
  );
  if (res.status !== 0) {
    throw new Error(`failed to load ${REGISTRY_JS}:\n${res.stderr}`);
  }
  return JSON.parse(res.stdout);
}

function buildPayload() {
  return {
    version: '2.0.0',
    description: 'Registered zone.type strings from src/zone-setup/registry.js ZONE_TYPES (generated by scripts/sync-zone-handlers.cjs)',
    handlers: [...new Set(readZoneTypes())].sort(),
  };
}

function main() {
  const payload = buildPayload();
  const text = JSON.stringify(payload, null, 2) + '\n';

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      const have = new Set(current ? JSON.parse(current).handlers || [] : []);
      const missing = payload.handlers.filter((h) => !have.has(h));
      const extra = [...have].filter((h) => !payload.handlers.includes(h));
      console.error('zone-handlers.json is out of date. Run: node scripts/sync-zone-handlers.cjs');
      if (missing.length) console.error(`  missing: ${missing.join(', ')}`);
      if (extra.length) console.error(`  stale:   ${extra.join(', ')}`);
      process.exit(1);
    }
    console.log(`zone-handlers.json is up to date (${payload.handlers.length} handlers)`);
    return;
  }

  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${payload.handlers.length} handlers)`);
}

if (require.main === module) {
  main();
}

module.exports = { buildPayload };
