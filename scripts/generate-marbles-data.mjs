#!/usr/bin/env node
/**
 * Generate src/marbles_data.js from the marble catalog:
 * assets/marbles/<id>.json, in the order of assets/manifest.json "marbles",
 * with restitution exceptions from assets/marbles/_bouncy-cap.json.
 *
 *   node scripts/generate-marbles-data.mjs           # write src/marbles_data.js
 *   node scripts/generate-marbles-data.mjs --check   # exit 1 if it is stale (CI)
 *
 * Fails (exit 1, nothing written) on id/name collisions, restitution above the
 * cap, marble files missing from the manifest, or any other catalog problem
 * (src/marbles/catalog-format.js findCatalogProblems).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
    bouncyCapLimits, findCatalogProblems, marbleDefToGameInfo,
} from '../src/marbles/catalog-format.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = path.join(ROOT, 'src', 'marbles_data.js');
const MARBLES_DIR = path.join(ROOT, 'assets', 'marbles');

/** @param {string} file */
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

/** Marble JSON files on disk (TEMPLATE.json and `_*.json` metadata excluded). */
export function marbleFilesOnDisk() {
    return fs.readdirSync(MARBLES_DIR)
        .filter((f) => f.endsWith('.json') && f !== 'TEMPLATE.json' && !f.startsWith('_'))
        .sort();
}

/**
 * @returns {{ infos: any[], problems: string[] }}
 */
export function loadCatalog() {
    const manifest = readJson(path.join(ROOT, 'assets', 'manifest.json'));
    const section = manifest.marbles || {};
    const bouncyCap = bouncyCapLimits(readJson(path.join(MARBLES_DIR, '_bouncy-cap.json')));
    /** @type {string[]} */
    const problems = [];
    /** @type {Array<{ key: string, def: any }>} */
    const entries = [];
    for (const [key, entry] of Object.entries(section)) {
        const file = path.join(ROOT, 'assets', String(entry.file).replace(/^assets\//, ''));
        if (!fs.existsSync(file)) {
            problems.push(`manifest.marbles.${key}: file not found (${entry.file})`);
            continue;
        }
        entries.push({ key, def: readJson(file) });
    }
    const listed = new Set(Object.values(section).map((e) => path.basename(String(e.file))));
    for (const f of marbleFilesOnDisk()) {
        if (!listed.has(f)) problems.push(`assets/marbles/${f} is not listed in manifest.json "marbles"`);
    }
    problems.push(...findCatalogProblems(entries, { bouncyCap }));
    return { infos: entries.map(({ def }) => marbleDefToGameInfo(def)), problems };
}

/** @param {unknown} v */
function literal(v) {
    if (Array.isArray(v)) return `[${v.map(literal).join(', ')}]`;
    if (v && typeof v === 'object') {
        return `{ ${Object.entries(v).map(([k, x]) => `${k}: ${literal(x)}`).join(', ')} }`;
    }
    return JSON.stringify(v);
}

/** @param {any[]} infos */
export function renderMarblesData(infos) {
    return `// GENERATED by scripts/generate-marbles-data.mjs from assets/marbles/*.json
// (ordered by assets/manifest.json "marbles"). Do not edit: change the JSON and
// run \`npm run gen:marbles\`. CI fails when this file is stale.
import { mergeRegistryMarbles as mergeInto } from './marbles/selection.js';

/** @type {Array<import('./marbles/catalog-format.js').MarbleInfo & Record<string, unknown>>} */
export const marblesInfo = [
${infos.map((info) => `    ${literal(info)},`).join('\n')}
];

/** Append registry marbles that aren't in the generated catalog (matched by id). */
export function mergeRegistryMarbles(registry) {
    return mergeInto(registry, marblesInfo);
}
`;
}

function main() {
    const check = process.argv.includes('--check');
    const { infos, problems } = loadCatalog();
    if (problems.length) {
        console.error(`✗ marble catalog problems:\n  - ${problems.join('\n  - ')}`);
        process.exit(1);
    }
    const source = renderMarblesData(infos);
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (check) {
        if (current !== source) {
            console.error('✗ src/marbles_data.js is stale — run `npm run gen:marbles`');
            process.exit(1);
        }
        console.log(`✓ src/marbles_data.js is up to date (${infos.length} marbles)`);
        return;
    }
    fs.writeFileSync(OUTPUT_PATH, source);
    console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${infos.length} marbles)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
